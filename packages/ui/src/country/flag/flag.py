for country_code in country_codes:
    # https://github.com/HatScripts/circle-flags
    url = f'https://hatscripts.github.io/circle-flags/flags/{country_code.lower()}.svg'
    res = requests.get(url)

    svg = res.text

    component = f'export function {country_code}() {{\nreturn (\n{svg}\n);\n}}\nexport default {country_code};\n'

    component = component.replace('<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512"><mask id="a"><circle cx="256" cy="256" r="256" fill="#fff"/></mask><g mask="url(#a)">', '<svg xmlns="http://www.w3.org/2000/svg" width="1em" height="1em" viewBox="0 0 512 512"><mask id="circle"><circle cx="256" cy="256" r="256" fill="#fff"/></mask><g mask="url(#circle)">')

    with open(f'{country_code}.tsx', "w") as f:
        f.write(component)

index = 'import Other from "./other";\n'

for country_code in country_codes:
    index += f'import {country_code} from "./{country_code}";\n'

index += 'export function Flag(props: { code: string }) {\nconst getFlag = (code: string) => {\ncode = code.toUpperCase();\n'

first = True
for country_code in country_codes:
    if first:
        index += f'if (code === "{country_code}") return <{country_code} />;\n'
        first = False
    else:
        index += f'else if (code === "{country_code}") return <{country_code} />;\n'

index += f'else return <Other />;\n'
index += '};\nreturn <div class="flex h-4 w-4 items-center justify-center">{getFlag(props.code)}</div>;\n};\n'

with open(f'index.tsx', "w") as f:
    f.write(index)
